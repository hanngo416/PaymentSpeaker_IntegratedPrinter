package model.view;

public class ChartBar {

    private String label;
    private String tip;
    private int x;
    private int width;
    private int barWidth;
    private int legitX;
    private int legitY;
    private int legitHeight;
    private int flaggedX;
    private int flaggedY;
    private int flaggedHeight;
    private int hitX;
    private int hitWidth;
    private int labelX;

    public String getLabel() {
        return label;
    }

    public void setLabel(String label) {
        this.label = label;
    }

    public String getTip() {
        return tip;
    }

    public void setTip(String tip) {
        this.tip = tip;
    }

    public int getX() {
        return x;
    }

    public void setX(int x) {
        this.x = x;
    }

    public int getWidth() {
        return width;
    }

    public void setWidth(int width) {
        this.width = width;
    }

    public int getBarWidth() {
        return barWidth;
    }

    public void setBarWidth(int barWidth) {
        this.barWidth = barWidth;
    }

    public int getLegitX() {
        return legitX;
    }

    public void setLegitX(int legitX) {
        this.legitX = legitX;
    }

    public int getLegitY() {
        return legitY;
    }

    public void setLegitY(int legitY) {
        this.legitY = legitY;
    }

    public int getLegitHeight() {
        return legitHeight;
    }

    public void setLegitHeight(int legitHeight) {
        this.legitHeight = legitHeight;
    }

    public int getFlaggedX() {
        return flaggedX;
    }

    public void setFlaggedX(int flaggedX) {
        this.flaggedX = flaggedX;
    }

    public int getFlaggedY() {
        return flaggedY;
    }

    public void setFlaggedY(int flaggedY) {
        this.flaggedY = flaggedY;
    }

    public int getFlaggedHeight() {
        return flaggedHeight;
    }

    public void setFlaggedHeight(int flaggedHeight) {
        this.flaggedHeight = flaggedHeight;
    }

    public int getHitX() {
        return hitX;
    }

    public void setHitX(int hitX) {
        this.hitX = hitX;
    }

    public int getHitWidth() {
        return hitWidth;
    }

    public void setHitWidth(int hitWidth) {
        this.hitWidth = hitWidth;
    }

    public int getLabelX() {
        return labelX;
    }

    public void setLabelX(int labelX) {
        this.labelX = labelX;
    }
}
